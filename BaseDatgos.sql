-- =====================================================================
-- BaseDatos.sql
-- Esquema de la solución. Cada microservicio tiene su propia base de datos
-- (patrón "Database per Service"): ninguno lee las tablas del otro.
--
--   clientes_db -> clientes-service (persona, cliente)
--   cuentas_db  -> cuentas-service  (cuenta, movimiento, cliente_snapshot)
--
-- Se ejecuta automáticamente al levantar el contenedor de PostgreSQL
-- (docker-entrypoint-initdb.d) o manualmente con:  psql -U banca -f BaseDatgos.sql
-- =====================================================================

CREATE DATABASE clientes_db;
CREATE DATABASE cuentas_db;

-- ---------------------------------------------------------------------
-- clientes_db
-- ---------------------------------------------------------------------
\connect clientes_db

-- Herencia JOINED: datos comunes en persona, datos propios en cliente.
CREATE TABLE persona (
                         id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre          VARCHAR(100) NOT NULL,
                         genero          VARCHAR(20)  CHECK (genero IN ('MASCULINO', 'FEMENINO', 'OTRO')),
                         edad            INTEGER      CHECK (edad >= 0),
                         identificacion  VARCHAR(20)  NOT NULL,
                         direccion       VARCHAR(200),
                         telefono        VARCHAR(20),
                         CONSTRAINT uk_persona_identificacion UNIQUE (identificacion)
);

CREATE TABLE cliente (
                         persona_id  BIGINT       PRIMARY KEY,
                         cliente_id  VARCHAR(50)  NOT NULL,
                         contrasena  VARCHAR(100) NOT NULL,          -- hash BCrypt, nunca texto plano
                         estado      BOOLEAN      NOT NULL DEFAULT TRUE,
                         CONSTRAINT uk_cliente_cliente_id UNIQUE (cliente_id),
                         CONSTRAINT fk_cliente_persona FOREIGN KEY (persona_id) REFERENCES persona (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- cuentas_db
-- ---------------------------------------------------------------------
\connect cuentas_db

-- Réplica local de clientes, alimentada por eventos de RabbitMQ.
CREATE TABLE cliente_snapshot (
                                  cliente_id     VARCHAR(50)  PRIMARY KEY,
                                  nombre         VARCHAR(100) NOT NULL,
                                  estado         BOOLEAN      NOT NULL,
                                  ultimo_evento  TIMESTAMP    NOT NULL
);

CREATE TABLE cuenta (
                        id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        numero_cuenta     VARCHAR(20)    NOT NULL,
                        tipo_cuenta       VARCHAR(20)    NOT NULL CHECK (tipo_cuenta IN ('AHORROS', 'CORRIENTE')),
                        saldo_inicial     NUMERIC(15, 2) NOT NULL CHECK (saldo_inicial >= 0),
                        saldo_disponible  NUMERIC(15, 2) NOT NULL CHECK (saldo_disponible >= 0),
                        estado            BOOLEAN        NOT NULL DEFAULT TRUE,
    -- Referencia lógica al cliente de otro microservicio: no puede ser FK entre bases distintas.
                        cliente_id        VARCHAR(50)    NOT NULL,
                        version           BIGINT         NOT NULL DEFAULT 0,  -- bloqueo optimista (@Version)
                        CONSTRAINT uk_cuenta_numero UNIQUE (numero_cuenta)
);

CREATE INDEX idx_cuenta_cliente ON cuenta (cliente_id);

CREATE TABLE movimiento (
                            id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            fecha            TIMESTAMP      NOT NULL,
                            tipo_movimiento  VARCHAR(20)    NOT NULL CHECK (tipo_movimiento IN ('DEPOSITO', 'RETIRO')),
                            valor            NUMERIC(15, 2) NOT NULL CHECK (valor <> 0),
                            saldo            NUMERIC(15, 2) NOT NULL CHECK (saldo >= 0),
                            cuenta_id        BIGINT         NOT NULL,
                            CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id)
);

-- Soporta el reporte de estado de cuenta (filtro por cuenta y rango de fechas).
CREATE INDEX idx_movimiento_cuenta_fecha ON movimiento (cuenta_id, fecha);
